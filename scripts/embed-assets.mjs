// Bundles the built app (dist/) into the Worker as a module, so it deploys with one upload.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
};

const root = 'dist';
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(root);

const entries = files.map((p) => {
  const path = '/' + relative(root, p).split('\\').join('/');
  const type = TYPES[extname(p)] ?? 'application/octet-stream';
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(readFileSync(p).toString('base64'))} },`;
});

writeFileSync(
  'worker/assets.gen.ts',
  `// Generated by scripts/embed-assets.mjs — do not edit\nexport const ASSETS: Record<string, { type: string; body: string }> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Embedded ${files.length} files`);
